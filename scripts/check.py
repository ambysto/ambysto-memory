#!/usr/bin/env python3
"""Check the ambysto-memory repo: lesson shape, INDEX.md, secret and identifying text, stale lessons.

Usage:
  python3 scripts/check.py                # check the working tree (tracked + untracked, not ignored)
  python3 scripts/check.py --staged       # check what is staged (the pre-commit hook)
  python3 scripts/check.py --write-index  # regenerate INDEX.md from lessons/, then check
  python3 scripts/check.py --root DIR     # check another folder (tests)

Exit 0 PASS, 1 FAIL, 2 usage error. Stale lessons are listed but do not fail the check.
Standard library only.
"""

import argparse
import collections
import datetime
import math
import os
import re
import subprocess
import sys

KINDS = ("workflow", "correction", "debugging_pattern", "gotcha", "convention", "decision", "reference")
FIELDS = ("title", "kind", "applies_when", "projects", "evidence", "last_validated", "status")
STALE_DAYS = 90
INDEX_HEADER = (
    "# Index\n"
    "\n"
    "Generated by `python3 scripts/check.py --write-index`; do not edit by hand. "
    "One line per active lesson: title, kind, when it applies.\n"
)

# Domains that may appear in a URL or as a host; a host passes when it equals one or ends in "." + one.
ALLOWED_DOMAINS = (
    "github.com",
    "githubusercontent.com",
    "microsoft.com",
    "nuget.org",
    "python.org",
    "anthropic.com",
    "claude.com",
    "ambysto.com",
    "digicert.com",
    "example.com",
    "example.org",
    "example.net",
)
ALLOWED_HOSTS = ("localhost", "127.0.0.1", "0.0.0.0", "10.0.2.2")  # 10.0.2.2: QEMU user-mode NAT host
# Product names that look like hosts under .NET; matched exactly, case-sensitively.
DOTNET_NAMES = ("ASP.NET", "ADO.NET", "VB.NET", "ML.NET", "Stryker.NET")
BARE_HOST_TLDS = ("com", "net", "org", "io", "dev", "ai", "co", "me", "cloud", "xyz", "vn")

SECRET_PATTERNS = (
    ("GitHub token", re.compile(r"\b(?:ghp|gho|ghs|ghu|ghr)_[A-Za-z0-9]{20,}")),
    ("GitHub token", re.compile(r"\bgithub_pat_[A-Za-z0-9_]{20,}")),
    ("API key", re.compile(r"\bsk-[A-Za-z0-9_-]{20,}")),
    ("Slack token", re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}")),
    ("AWS key id", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("private key", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    ("Plane API key", re.compile(r"(?i)plane_api_[0-9a-z]{8,}")),
    ("bearer token", re.compile(r"(?i)\bbearer\s+[A-Za-z0-9._~+/-]{16,}")),
    ("credential assignment",
     re.compile(r"(?i)(?<![A-Za-z])(?:password|passwd|token|secret|api[_-]?key)\s*=\s*['\"]?[^\s'\"`]{8,}")),
    ("credential assignment",
     re.compile(r"(?i)(?<![A-Za-z])(?:password|passwd|token|secret|api[_-]?key)\s*:\s*['\"]?"
                r"(?=[^\s'\"`]*[0-9])(?=[^\s'\"`]*[A-Za-z])[^\s'\"`:/~.,]{16,}")),
    ("UUID", re.compile(r"(?<![0-9A-Fa-f])[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"
                        r"(?![0-9A-Fa-f])")),
    ("e-mail address", re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}")),
    # A drive letter before /Users/ means a Windows path (the VM's C:/Users/ambytest/), not a Mac home.
    ("absolute home path", re.compile(r"(?<![A-Za-z]:)/(?:home|Users)/[A-Za-z0-9._-]+/")),
    # Claude Code encodes a project folder as -home-<account>-work-…; the account name must not reach GitHub.
    ("encoded home path", re.compile(r"(?:^|[\s`'\"/(\[])-(?:home|Users)-[A-Za-z0-9]")),
    ("Vercel deployment host", re.compile(r"(?i)\b[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.vercel\.app\b")),
)
# Hex and base64 runs are bounded by lookarounds, not \b: `_` is a word character, so a key after a
# prefix such as `name_` would never start at a word boundary.
HEX_RUN = re.compile(r"(?<![0-9A-Fa-f])[0-9a-fA-F]{13,}(?![0-9A-Fa-f])")
# Random keys measure 4.6 bits per character or more; real paths and identifiers of that length 4.2 or less.
B64_MIN_ENTROPY = 4.4
B64_RUN = re.compile(r"(?<![A-Za-z0-9+/_=-])[A-Za-z0-9+/_-]{32,}={0,2}")
URL = re.compile(r"\b[a-zA-Z][a-zA-Z0-9+.-]*://([^/\s'\"`<>()\[\]]+)")
SCHEMELESS_URL = re.compile(r"(?<![:\w/])//([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+)")
# A version (AmbystoLean_1.0.0.0_x64, Version="1.0.0.0", "AssemblyVersion 2.1.3.0") is not an address;
# a trailing full stop still ends one.
IPV4 = re.compile(r"(?<![\w.=\"'-])((?:\d{1,3}\.){3}\d{1,3})(?!\.?\d)(?![\w\"'-])")
VERSION_WORD = re.compile(r"(?i)version\W{0,3}$")
BARE_HOST = re.compile(
    r"(?i)(?<![\w@/.-])((?:[A-Za-z0-9-]+\.)+(?:" + "|".join(BARE_HOST_TLDS) + r"))(?![\w-])"
)
SLUG = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*\.md$")
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def entropy(text):
    """Shannon entropy in bits per character."""
    counts = collections.Counter(text)
    return -sum(c / len(text) * math.log2(c / len(text)) for c in counts.values())


def host_allowed(host):
    host = host.lower().rstrip(".")
    if host in ALLOWED_HOSTS:
        return True
    return any(host == d or host.endswith("." + d) for d in ALLOWED_DOMAINS)


def secret_findings(text):
    """Yield (line number, reason) for every refused value in text."""
    for n, line in enumerate(text.splitlines(), 1):
        for reason, pattern in SECRET_PATTERNS:
            if pattern.search(line):
                yield n, reason
        for m in HEX_RUN.finditer(line):
            run = m.group(0)
            if re.search(r"[0-9]", run) and re.search(r"[a-fA-F]", run):
                yield n, "hex run of %d characters (a full SHA or a key; cite a PR, ticket or short SHA)" % len(run)
        for m in B64_RUN.finditer(line):
            run = m.group(0)
            if re.search(r"[a-z]", run) and re.search(r"[A-Z]", run) and entropy(run) >= B64_MIN_ENTROPY:
                yield n, "base64-like run of %d characters" % len(run)
        for m in URL.finditer(line):
            host = m.group(1).rsplit("@", 1)[-1]
            host = re.sub(r":\d+$", "", host)
            if not host_allowed(host):
                yield n, "URL host not on the allow list: %s" % host
        for m in SCHEMELESS_URL.finditer(line):
            if not host_allowed(m.group(1)):
                yield n, "URL host not on the allow list: %s" % m.group(1)
        for m in IPV4.finditer(line):
            ip = m.group(1)
            if VERSION_WORD.search(line[:m.start()]):
                continue
            if all(int(part) <= 255 for part in ip.split(".")) and ip not in ALLOWED_HOSTS:
                yield n, "IPv4 address: %s" % ip
        for m in BARE_HOST.finditer(line):
            if m.group(1) in DOTNET_NAMES:
                continue
            if not host_allowed(m.group(1)):
                yield n, "host not on the allow list: %s" % m.group(1)


def parse_lesson(text):
    """Return (fields dict, body lines, error). Frontmatter is `key: value` lines between --- lines."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None, None, "no frontmatter (first line must be ---)"
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        return None, None, "frontmatter not closed"
    fields = {}
    for raw in lines[1:end]:
        if not raw.strip():
            continue
        m = re.match(r"^([a-z_]+):\s*(.*)$", raw)
        if not m:
            return None, None, "frontmatter line is not `key: value`: %r" % raw
        key, value = m.group(1), m.group(2).strip()
        if key in fields:
            return None, None, "frontmatter key repeated: %s" % key
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        fields[key] = value
    return fields, [l for l in lines[end + 1:] if l.strip()], None


def parse_projects(value):
    if value == "all":
        return ["all"]
    m = re.match(r"^\[(.*)\]$", value)
    if not m:
        return None
    items = [p.strip() for p in m.group(1).split(",")]
    if not items or any(not re.match(r"^[a-z0-9][a-z0-9-]*$", p) for p in items):
        return None
    return items


def check_lessons(files, today):
    """Return (errors, stale, active lessons as (slug, fields))."""
    errors, stale, lessons = [], [], {}
    for path in sorted(files):
        if not path.startswith("lessons/") or path == "lessons/.gitkeep":
            continue
        name = path[len("lessons/"):]
        if "/" in name or not SLUG.match(name):
            errors.append((path, 0, "lesson file name must be a slug: lowercase letters, digits, hyphens, .md"))
            continue
        fields, body, err = parse_lesson(files[path])
        if err:
            errors.append((path, 1, err))
            continue
        lessons[name[:-3]] = fields
        for key in FIELDS:
            if not fields.get(key):
                errors.append((path, 1, "missing field: %s" % key))
        for key in fields:
            if key not in FIELDS + ("superseded_by",):
                errors.append((path, 1, "unknown field: %s" % key))
        title = fields.get("title", "")
        if len(title) >= 80:
            errors.append((path, 1, "title is %d characters (under 80)" % len(title)))
        kind = fields.get("kind")
        if kind and kind not in KINDS:
            errors.append((path, 1, "kind %r is not one of %s" % (kind, ", ".join(KINDS))))
        when = fields.get("applies_when", "")
        if when and not re.match(r"^(when|before|after)\b", when):
            errors.append((path, 1, "applies_when must start with when, before or after"))
        if fields.get("projects") and parse_projects(fields["projects"]) is None:
            errors.append((path, 1, "projects must be `all` or a list like [ambysto-space, steady]"))
        validated = fields.get("last_validated", "")
        if validated:
            try:
                if not DATE.match(validated):
                    raise ValueError
                date = datetime.date.fromisoformat(validated)
            except ValueError:
                errors.append((path, 1, "last_validated must be a date YYYY-MM-DD"))
            else:
                if date > today:
                    errors.append((path, 1, "last_validated is in the future"))
                elif (today - date).days > STALE_DAYS and fields.get("status") == "active":
                    stale.append((path, validated))
        status = fields.get("status")
        if status and status not in ("active", "superseded"):
            errors.append((path, 1, "status must be active or superseded"))
        if status == "superseded" and not fields.get("superseded_by"):
            errors.append((path, 1, "a superseded lesson needs superseded_by"))
        if status == "active" and fields.get("superseded_by"):
            errors.append((path, 1, "an active lesson has no superseded_by"))
        if not 3 <= len(body) <= 10:
            errors.append((path, 1, "body has %d non-empty lines (3 to 10)" % len(body)))
    for slug, fields in lessons.items():
        target = fields.get("superseded_by")
        if target and target not in lessons:
            errors.append(("lessons/%s.md" % slug, 1, "superseded_by names no lesson: %s" % target))
    active = [(slug, f) for slug, f in lessons.items() if f.get("status") == "active"]
    return errors, stale, active


def render_index(active):
    rows = sorted(active, key=lambda item: (item[1].get("kind", ""), item[1].get("title", "").lower()))
    text = INDEX_HEADER
    if rows:
        text += "\n" + "".join(
            "- [%s](lessons/%s.md) — %s — %s\n" % (f.get("title", ""), slug, f.get("kind", ""), f.get("applies_when", ""))
            for slug, f in rows
        )
    return text


def git(root, *args):
    return subprocess.run(["git", "-C", root] + list(args), capture_output=True, check=True).stdout


def load_files(root, staged):
    """Return {path: text} for the files that would be committed, or that the working tree holds."""
    if staged:
        names = git(root, "diff", "--cached", "--name-only", "--diff-filter=d", "-z").split(b"\0")
        names += git(root, "ls-files", "-z").split(b"\0")
    else:
        names = git(root, "ls-files", "--cached", "--others", "--exclude-standard", "-z").split(b"\0")
    files, errors = {}, []
    for raw in sorted(set(n for n in names if n)):
        path = raw.decode("utf-8", "replace")
        if staged:
            try:
                data = git(root, "show", ":" + path)
            except subprocess.CalledProcessError:
                continue  # deleted in the index
        else:
            full = os.path.join(root, path)
            if not os.path.isfile(full):
                continue
            with open(full, "rb") as fh:
                data = fh.read()
        try:
            files[path] = data.decode("utf-8")
        except UnicodeDecodeError:
            errors.append((path, 0, "not UTF-8 text (this repo holds text only)"))
    return files, errors


def main(argv=None):
    parser = argparse.ArgumentParser(description="Check the ambysto-memory repo.")
    parser.add_argument("--staged", action="store_true", help="check the staged files (pre-commit hook)")
    parser.add_argument("--write-index", action="store_true", help="regenerate INDEX.md, then check")
    parser.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    parser.add_argument("--today", help=argparse.SUPPRESS)  # tests: YYYY-MM-DD
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return 2 if exc.code else 0
    if args.staged and args.write_index:
        print("--staged and --write-index cannot be combined", file=sys.stderr)
        return 2
    today = datetime.date.fromisoformat(args.today) if args.today else datetime.date.today()
    root = os.path.abspath(args.root)
    try:
        files, errors = load_files(root, args.staged)
    except (OSError, subprocess.CalledProcessError) as exc:
        print("cannot list the repo's files: %s" % exc, file=sys.stderr)
        return 2

    lesson_errors, stale, active = check_lessons(files, today)
    errors += lesson_errors
    index = render_index(active)
    if args.write_index:
        with open(os.path.join(root, "INDEX.md"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(index)
        files["INDEX.md"] = index
    if files.get("INDEX.md") != index:
        errors.append(("INDEX.md", 0, "not equal to the lessons; run `python3 scripts/check.py --write-index`"))
    for path in sorted(files):
        for n, reason in secret_findings(files[path]):
            errors.append((path, n, "refused: " + reason))

    for path, validated in stale:
        print("STALE: %s (last_validated %s, over %d days): review it with the owner" % (path, validated, STALE_DAYS))
    if errors:
        for path, n, reason in sorted(errors):
            print("%s:%d: %s" % (path, n, reason))
        print("FAIL: %d problem(s)" % len(errors))
        return 1
    print("PASS: %d active lesson(s), %d file(s) checked" % (len(active), len(files)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
